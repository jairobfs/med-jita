import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const read=p=>readFileSync(p,'utf8');
const catalog=JSON.parse(read('site-v51/source/catalog.json'));
const html=read('site-v51/source/identidade.html');
const workflow=read('.github/workflows/publicar.yml');
const brand=read('site-v51/source/integrations/med-brand-system.js');
const engine=read('site-v51/source/integrations/uc-engine.js');
assert.ok(catalog.modules.length>=16);
assert.ok(catalog.grades.length>=30);
assert.equal(new Set(catalog.modules.map(x=>x.id)).size,catalog.modules.length);
assert.equal(new Set(catalog.grades.map(x=>x.id)).size,catalog.grades.length);
for(const m of engine.matchAll(/tpl\(['"]([^'"]+)['"]/g))assert.ok(catalog.modules.some(x=>x.id===m[1]),'Módulo sem ícone: '+m[1]);
for(const m of engine.matchAll(/(?:graded|points)\(['"]([^'"]+)['"]/g))assert.ok(catalog.grades.some(x=>x.id===m[1]),'Nota sem ícone: '+m[1]);
assert.match(html,/med-brand-system\.js/);
assert.match(html,/jita-corpo\.svg/);
assert.match(html,/data-filter/);
assert.match(html,/aria-pressed/);
assert.match(brand,/jita-audio-toggle/);
assert.match(workflow,/node tests\/v53-gallery\.spec\.mjs/);
for(const p of ['catalog.json','identidade.html','jita-curricular.css','med-brand-system.js','med-jita-brand-v11.svg','jita-corpo.svg'])assert.ok(workflow.includes('_site/identidade/'+(p==='identidade.html'?'index.html':p)),'Artefato não publicado: '+p);
for(const item of catalog.modules)assert.match(item.accent,/^#[0-9A-Fa-f]{6}$/);
new vm.Script(html.match(/<script>([\s\S]+)<\/script>/)?.[1]||'');
console.log('Galeria V53 OK:',catalog.modules.length,'selos de módulo,',catalog.grades.length,'de notas; saída isolada da calculadora.');
